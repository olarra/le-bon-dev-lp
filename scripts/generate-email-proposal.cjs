const fs = require("node:fs")
const path = require("node:path")
const vm = require("node:vm")
const ts = require("typescript")

const root = path.resolve(__dirname, "..")
const modules = new Map()

// Execute the existing TypeScript builders without adding a preview route or
// another runtime dependency. Transpilation here only produces the HTML artifact.
function loadSource(filename) {
  if (!filename.endsWith(".ts")) filename += ".ts"
  if (modules.has(filename)) return modules.get(filename).exports
  const sourceModule = { exports: {} }
  modules.set(filename, sourceModule)
  const { outputText } = ts.transpileModule(fs.readFileSync(filename, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true },
    fileName: filename,
  })
  const localRequire = specifier => {
    if (specifier.startsWith("@/")) return loadSource(path.join(root, specifier.slice(2)))
    if (specifier.startsWith(".")) return loadSource(path.resolve(path.dirname(filename), specifier))
    return require(specifier)
  }
  vm.compileFunction(outputText, ["require", "module", "exports"], { filename })(localRequire, sourceModule, sourceModule.exports)
  return sourceModule.exports
}

