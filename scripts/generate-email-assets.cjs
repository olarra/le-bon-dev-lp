/* Generate hosted PNGs and the local CID fallback; does not send mail. */
const fs = require("node:fs/promises")
const path = require("node:path")
const sharp = require("sharp")

async function generate() {
  const root = path.resolve(__dirname, "..")
  const logo = await fs.readFile(path.join(root, "public/logo-le-bon-dev.svg"), "utf8")
  const mark = await fs.readFile(path.join(root, "public/images/brand/le-bon-dev-mark-white.svg"), "utf8")
  const sources = [
    ["wordmark", 368, logo.replaceAll("#1B4040", "#F4F2EC").replaceAll("#0A0B0A", "#F4F2EC")],
    ["mark-lime", 152, mark.replaceAll('"white"', '"#C8F53E"')],
    ["mark-forest", 110, mark.replaceAll('"white"', '"#203E33"')],
  ]
  const publicDirectory = path.join(root, "public/images/email")
  await fs.mkdir(publicDirectory, { recursive: true })
  const attachments = []
  for (const [name, width, svg] of sources) {
    const png = await sharp(Buffer.from(svg)).resize({ width }).png().toBuffer()
    const filename = `le-bon-dev-${name}.png`
    await fs.writeFile(path.join(publicDirectory, filename), png)
    attachments.push({
      contentType: "image/png",
      filename,
      contentId: `lebondev-${name}`,
      publicPath: `/images/email/${filename}`,
      base64Content: png.toString("base64"),
    })
  }
  const destination = path.join(root, "lib/email/assets.ts")
  await fs.mkdir(path.dirname(destination), { recursive: true })
  await fs.writeFile(destination,
    '// Generated by scripts/generate-email-assets.cjs from the studio SVGs.\n' +
    '// Public PNGs have the same artwork; inline data is the local-only fallback.\n' +
    'import type { EmailAsset } from "./types"\n\n' +
    'export const EMAIL_ASSETS: readonly EmailAsset[] = ' + JSON.stringify(attachments, null, 2) + '\n',
  )
}

generate().catch(error => { console.error(error); process.exitCode = 1 })
